#!/usr/bin/env node
// Install (or update) the presentation pack into an open tldraw deck.
//   node bin/install.mjs <doc name | path.tldraw> [--ext <deck ext folder>]
// Replaces the deck's board script with this pack's script/ folder, waits for the app to apply
// it, and saves the deck. Slides and deck settings are untouched.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { request, exec, findDoc, sleep, parseArgs } from './tl.mjs'

const PACK_SCRIPT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../script')

// `ext` (optional): a deck's extension folder (decks/<slug>/ext). Its files go to script/ext/, with
// `@pack/…` imports rewritten to relative paths, and script/extensions.js is generated to load it.
export async function install(doc, { ext } = {}) {
	if (doc.ownership !== 'local') throw new Error(`${doc.name} is not a local document; the host must install the pack.`)
	const ws = await request('POST', `/api/doc/${doc.id}/script-workspace`)
	const dest = ws.scriptDir

	// Everything the deck's script dir should hold: rel path → file contents.
	const want = new Map()
	for (const rel of listFiles(PACK_SCRIPT)) want.set(rel, fs.readFileSync(path.join(PACK_SCRIPT, rel)))
	if (ext && fs.existsSync(path.join(ext, 'index.js'))) {
		for (const rel of listFiles(ext)) {
			let data = fs.readFileSync(path.join(ext, rel))
			if (rel.endsWith('.js')) {
				const up = '../'.repeat(rel.split(path.sep).length)
				data = Buffer.from(data.toString('utf8').replace(/(['"])@pack\//g, `$1${up}`))
			}
			want.set(path.join('ext', rel), data)
		}
		want.set('extensions.js', Buffer.from(
			"// Generated by bin/install.mjs: this deck's extension (see decks/<slug>/ext).\n" +
			"import ext from './ext/index.js'\n" +
			'export const EXTENSIONS = [ext]\n' +
			'export const fromExtensions = (key) => Object.assign({}, ...EXTENSIONS.map((e) => e?.[key] ?? {}))\n'))
	}

	// Mirror: remove files that shouldn't be there, write the rest (only when changed).
	for (const rel of listFiles(dest)) if (!want.has(rel)) fs.rmSync(path.join(dest, rel))
	for (const [rel, data] of want) {
		const to = path.join(dest, rel)
		if (fs.existsSync(to) && fs.readFileSync(to).equals(data)) continue
		fs.mkdirSync(path.dirname(to), { recursive: true })
		fs.writeFileSync(to, data)
	}

	let status
	for (let i = 0; i < 40; i++) {
		await sleep(500)
		status = await request('GET', `/api/doc/${doc.id}/script-status`)
		if (status.state === 'applied' || status.state === 'error') break
	}
	if (status.state !== 'applied') {
		const log = fs.existsSync(ws.errorLogPath) ? fs.readFileSync(ws.errorLogPath, 'utf8') : ''
		throw new Error(`Script not applied (state: ${status.state}). ${status.lastApplyError ?? ''}\n${log}`)
	}
	await sleep(800)
	const runs = await request('GET', `/api/doc/${doc.id}/scripts`)
	if (runs.boardScript?.status === 'error') throw new Error(`Board script failed: ${JSON.stringify(runs.boardScript.lastError)}`)
	await exec(doc.id, 'await helpers.saveDoc(); return true')
	return { scriptDir: dest, files: want.size }
}

function listFiles(dir, base = dir) {
	if (!fs.existsSync(dir)) return []
	return fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
		const p = path.join(dir, e.name)
		return e.isDirectory() ? listFiles(p, base) : [path.relative(base, p)]
	})
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	const args = parseArgs(process.argv.slice(2))
	if (!args._[0]) {
		console.error('usage: node bin/install.mjs <doc name | path.tldraw>')
		process.exit(1)
	}
	try {
		const doc = await findDoc(args._[0])
		const r = await install(doc, { ext: args.ext ? path.resolve(String(args.ext)) : undefined })
		console.log(`Installed presentation pack (${r.files} files) into "${doc.name}" and saved.`)
	} catch (e) {
		console.error(e.message)
		process.exit(1)
	}
}
